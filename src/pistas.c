const char *obterTextoAjuda(const Pergunta *pergunta, TipoAjuda tipo){
    if (pergunta == NULL || (tipo != AJUDA_MISSAO && tipo != AJUDA_TELESCOPIO)){
        return NULL;
    }

    // Uma pergunta nova ou com enunciado alterado precisa de conteúdo próprio.
    for (size_t i = 0; i < sizeof(conteudos) / sizeof(conteudos[0]); i++){
        if (conteudos[i].id == pergunta->id &&
            strcmp(conteudos[i].enunciado, pergunta->enunciado) == 0){
            return tipo == AJUDA_MISSAO ? conteudos[i].pista : conteudos[i].informacao;
        }
    }
    return NULL;
}
